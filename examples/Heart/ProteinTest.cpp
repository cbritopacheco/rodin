/**
 * @file ProteinTest.cpp
 * @brief Minimal testbed for the coagulation kinetics on a simplified
 *        coronary-like geometry: one inlet, one outlet, one wall, and a
 *        traction-free outlet.
 *
 * Why this geometry. A straight conduit is the wrong test. Its residence time
 * is of order 0.1 s, and the closed-reactor estimate below shows that the
 * kinetics then convert about 1e-5 of the available fibrinogen -- indistinguishable
 * from zero. The mesh generated by ProteinTest/make_test_mesh.py is therefore a
 * straight tube carrying an ectatic segment (radius 1.5 mm widening to 4.5 mm,
 * expansion ratio 3), which produces a recirculation bubble. The point of the
 * test is that both regimes are present in one run: the conduit shows nothing
 * and the pouch does, which is what tells you the model discriminates rather
 * than merely producing a number.
 *
 * How much residence time is needed. Treating the pouch as a closed reactor fed
 * by a wall flux, Th(t) = R_th S t with S = A/V the surface-to-volume ratio, and
 *
 *     Fg(t) = Fg0 exp( -k_eff R_th S t^2 / 2 ),   Fn = Fg0 - Fg,
 *
 * so a one per cent conversion needs t_res = sqrt( 0.02 / (k_eff R_th S) ).
 * With S ~ 1e3 1/m this is about 5 s, i.e. six cycles; a fully formed clot
 * needs of order a minute. Those are the numbers to check the run against, and
 * they are printed at startup.
 *
 * A washout field is solved alongside the species so that this can be verified
 * rather than assumed:
 *
 *     dc/dt + u.grad c = 0,   c = 1 at t0,   c = 0 at the inlet,
 *
 * with c the surviving fraction of the original bolus. The reported number is
 * the volume-weighted residual R(t) = (1/V) int c dV and its decay constant.
 * This replaces the Eulerian age field dT/dt + u.grad T = 1, which is not
 * reportable: on closed streamlines T grows without bound, so what you read off
 * is how long you ran rather than a property of the flow. c is bounded in
 * [0, 1] and R converges, so it is comparable between geometries.
 *
 * The outlet carries no Windkessel and no R_mu closure: p_out = 0. That is
 * deliberate. The quantity the whole test hinges on is how long blood is held,
 * and a rheology-dependent nonlinear outlet would sit between the geometry and
 * that quantity, so a washout that came out too fast could no longer be
 * attributed to the geometry alone.
 *
 * One loop, flow solved every step. The coupling is one-way, so the flow could
 * be solved for a few cycles, recorded, and replayed while only the species
 * advance -- and an earlier version did exactly that. It is dropped here: it
 * bought speed with an array of PETSc Vecs and a VecDuplicate/VecCopy/
 * VecDestroy layer that appears nowhere else in this tree, and it turned the
 * velocity from a solution into a recording. The flow is about three quarters
 * of a step, so solving it throughout costs
 * (flowCycles + speciesCycles)/flowCycles times more -- and it holds one
 * velocity field rather than one per step of a cycle, so it is the smaller
 * memory footprint too. -pt_flow_cycles is the warm-up before the species
 * switch on, -pt_species_cycles how long they then run.
 *
 * @see CoronaryArtery/ThrombosisModel.h for the kinetics and the scope of the
 *      model.
 */
