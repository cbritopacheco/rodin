#!/usr/bin/env python3
"""
Presentation video of a KnifeGateValve run: volume rendering of the speed
|u| (time evolution, interpolated between the saved snapshots), with the
valve (body, liner, knife from the STEP) as transparent solids for
reference, and a slow camera orbit.

  python3 valve_video.py runs_seat/FPC8-rampup_open025 -o rampup_025.mp4
  python3 valve_video.py <case> --preview            # one PNG, to check the view
  python3 valve_video.py <case> --quality high -o x.mp4   # 1920x1080, finer volume

The case folder is a run_valves*.sh output folder (XDMF + case.env). The
valve solids are read from resources/examples/Valve/cad/<valve>_{body,liner,
knife}.stl (STEP in mm, generated by make_meshes.py's export); the knife is
moved to the opening of the case as in the meshes. The CAD liner is drawn
whatever the seat design (it is only a visual reference).

Needs: pip install pyvista imageio imageio-ffmpeg h5py (VTK comes with
pyvista; off screen rendering works without a display).
"""
import argparse
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import postprocess_valves as pv_  # noqa: E402
import make_meshes as mm  # noqa: E402

import pyvista as pv  # noqa: E402

pv.OFF_SCREEN = True

QUALITY = {
    "draft": dict(size=(1280, 720), res=3.0e-3, sub=2, fps=24),
    "normal": dict(size=(1600, 900), res=2.0e-3, sub=3, fps=30),
    "high": dict(size=(1920, 1080), res=1.5e-3, sub=4, fps=30),
}


def load_grid(base, ranks, cache):
    """One VTK unstructured grid with the tetrahedra of all ranks (the ghost
    copies overlap, harmless for probing), and per-rank node offsets."""
    meshes = pv_.load_mesh(base, ranks, cache)
    pts, cells, offs, off = [], [], [], 0
    for V, T in meshes:
        pts.append(V)
        cells.append(np.hstack([np.full((len(T), 1), 4, np.int64), T + off]))
        offs.append(off)
        off += len(V)
    P = np.vstack(pts)
    C = np.vstack(cells).ravel()
    grid = pv.UnstructuredGrid(C, np.full(len(C) // 5, 10, np.uint8), P)  # 10 = VTK_TETRA
    return grid, meshes


def speed(base, ranks, meshes):
    return np.concatenate([np.linalg.norm(pv_.h5(base, r["velocity"]).reshape(-1, 3), axis=1)
                           for (V, T), r in zip(meshes, ranks)])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("case", help="case folder, e.g. runs_seat/FPC8-rampup_open025")
    ap.add_argument("-o", "--out", default=None, help="output .mp4 (default: <case>.mp4)")
    ap.add_argument("--cad", default=os.path.join(HERE, "..", "..", "resources", "examples", "Valve", "cad"))
    ap.add_argument("--quality", default="normal", choices=list(QUALITY))
    ap.add_argument("--z", type=float, nargs=2, default=(-1.0, 4.0),
                    help="extent of the volume along the pipe, in D from the knife (default -1 4)")
    ap.add_argument("--tmin", type=float, default=None, help="first time [s] (default: the first snapshot)")
    ap.add_argument("--max-snaps", type=int, default=120, help="at most this many snapshots (evenly picked)")
    ap.add_argument("--vmax", type=float, default=None, help="top of the colour scale [m/s] (default: 99th percentile)")
    ap.add_argument("--orbit", type=float, default=50.0, help="camera sweep over the video [deg]")
    ap.add_argument("--azimuth", type=float, default=-160.0,
                    help="start azimuth of the camera [deg] (-90: from upstream, 180/-180: side)")
    ap.add_argument("--elevation", type=float, default=22.0, help="camera elevation [deg]")
    ap.add_argument("--opacity", type=float, default=1.0, help="scale of the volume opacity (more: denser jet)")
    ap.add_argument("--hold", type=float, default=2.0, help="seconds of still title frames at the start")
    ap.add_argument("--title", default=None, help="title line (default from the case)")
    ap.add_argument("--subtitle", default=None)
    ap.add_argument("--preview", action="store_true", help="only one PNG of the last snapshot")
    ap.add_argument("--aa", action="store_true", help="FXAA anti-aliasing (only with a real GPU/display)")
    ap.add_argument("--peel", action="store_true", help="depth peeling (only with a real GPU/display)")
    a = ap.parse_args()
    Q = QUALITY[a.quality]

    case = a.case.rstrip("/")
    tag = os.path.basename(case)
    valve, opening = tag.split("_open")
    opening = int(opening)
    base_valve, _, design = valve.partition("-")
    v = mm.VALVES[base_valve]
    R = v["R"] * 1e-3
    D = 2 * R
    out = a.out or (tag + (".png" if a.preview else ".mp4"))

    base, steps = pv_.read_xdmf(os.path.join(case, tag + ".xdmf"))
    if a.tmin is not None:
        steps = [s for s in steps if s[0] >= a.tmin] or steps[-1:]
    if a.preview:
        steps = steps[-1:]
    if len(steps) > a.max_snaps:
        idx = np.unique(np.linspace(0, len(steps) - 1, a.max_snaps).round().astype(int))
        steps = [steps[i] for i in idx]
    env = pv_.read_env(case)
    print(f"[{tag}] {len(steps)} snapshots, t in [{steps[0][0]:.4f}, {steps[-1][0]:.4f}] s")

    # ---- volume grid (only the pipe region around the valve) ----------------
    cache = {}
    grid, meshes = load_grid(base, steps[0][1], cache)
    z0, z1 = a.z[0] * D, a.z[1] * D
    h = Q["res"]
    nx = int(round(2 * R / h)) + 1
    nz = int(round((z1 - z0) / h)) + 1
    img = pv.ImageData(dimensions=(nx, nx, nz), spacing=(2 * R / (nx - 1),) * 2 + ((z1 - z0) / (nz - 1),),
                       origin=(-R, -R, z0))
    print(f"[{tag}] volume {nx} x {nx} x {nz} = {img.n_points / 1e6:.1f} M voxels")

    def sample(ranks):
        grid.point_data["s"] = speed(base, ranks, meshes)
        s = img.sample(grid, pass_point_data=False)
        val = np.asarray(s.point_data["s"]).copy()
        val[np.asarray(s.point_data["vtkValidPointMask"]) == 0] = 0.0
        return val

    vols = []
    for i, (t, ranks) in enumerate(steps):
        vols.append(sample(ranks))
        print(f"  sampled {i + 1}/{len(steps)}  t = {t:.4f} s", end="\r", flush=True)
    print()
    vmax = a.vmax or float(np.percentile(np.concatenate([x[x > 0] for x in vols[-min(10, len(vols)):]]), 99.5))
    print(f"[{tag}] colour scale 0 .. {vmax:.2f} m/s")

    # ---- scene ---------------------------------------------------------------
    p = pv.Plotter(off_screen=True, window_size=Q["size"])
    p.set_background("#05070d", top="#1b2433")
    if a.aa:  # off by default: with the OSMesa/EGL VTK of the pip wheels it hides the volume
        p.enable_anti_aliasing("fxaa")
    if a.peel:  # translucent solids blended with the volume (GPU)
        p.enable_depth_peeling(number_of_peels=8, occlusion_ratio=0.0)
        p.renderer.SetUseDepthPeelingForVolumes(True)
    s_mm = 1e-3
    dy = (opening / 100.0 * (v["R"] + v["Rk"] - 0.0079 * 2 * v["R"]) - v["yc_cad"]) * s_mm
    solids = {}
    for part, color, opacity, spec in (("body", "#9aa6b2", 0.10, 0.6), ("liner", "#d9a441", 0.16, 0.3),
                                       ("knife", "#c8ced6", 0.30, 0.9)):
        fn = os.path.join(a.cad, f"{base_valve}_{part}.stl")
        if not os.path.isfile(fn):
            print("  (no", fn, ")")
            continue
        m = pv.read(fn).scale(s_mm, inplace=False)
        if part == "knife":
            m = m.translate((0.0, dy, 0.0), inplace=False)
        m = m.clip("y", origin=(0, 1.6 * R, 0), invert=True)  # drop the bonnet and the knife stem
        m = m.clip_box((-1, 1, -1, 1, z0 - 0.3 * D, z1 + 0.3 * D), invert=False) if part == "body" else m
        solids[part] = p.add_mesh(m, color=color, opacity=opacity, smooth_shading=True, specular=spec,
                                  specular_power=30, show_edges=False)
    # pipe outline: two faint rings and a transparent tube
    tube = pv.Cylinder(center=(0, 0, 0.5 * (z0 + z1)), direction=(0, 0, 1), radius=R, height=z1 - z0,
                       resolution=120, capping=False)
    p.add_mesh(tube, color="#7f93a8", opacity=0.06, smooth_shading=True)
    for zz in (z0, z1):
        p.add_mesh(pv.Circle(radius=R, resolution=180).translate((0, 0, zz), inplace=False).extract_feature_edges(),
                   color="#8fb3d9", line_width=2, opacity=0.6)

    vol_img = img.copy()
    vol_img.point_data["|u| [m/s]"] = vols[-1] if a.preview else vols[0]
    # transfer function: the slow fluid transparent, the jet and the shear
    # layers bright; opacities per 1 cm of fluid crossed
    opacity = np.array([0.0, 0.0, 0.03, 0.12, 0.30, 0.55, 0.80, 0.95]) * a.opacity
    vol = p.add_volume(vol_img, scalars="|u| [m/s]", cmap="turbo", clim=(0, vmax), opacity=opacity,
                       shade=False, mapper="smart", show_scalar_bar=False, blending="composite",
                       opacity_unit_distance=0.01)
    vol.prop.interpolation_type = "linear"
    # colour bar from an invisible mesh with the same colour map (the one of
    # the volume shows the colours multiplied by the opacity ramp)
    dummy = pv.PolyData(np.zeros((2, 3)))
    dummy.point_data["speed"] = [0.0, vmax]
    bar_actor = p.add_mesh(dummy, scalars="speed", cmap="turbo", clim=(0, vmax), opacity=0.0,
                           show_scalar_bar=False, render_points_as_spheres=False, point_size=0.1)
    p.add_scalar_bar("velocidad [m/s]", mapper=bar_actor.mapper, vertical=True, position_x=0.90, position_y=0.22, height=0.55, width=0.035,
                     color="white", title_font_size=18, label_font_size=15, n_labels=5, fmt="%.0f")
    names = {"cad": "cad (original)", "fillet": "fillet", "chamfer": "chamfer", "upramp": "upramp",
             "rampup": "rampup", "rampdn": "rampdn", "lip": "lip"}
    title = a.title or f"Válvula de cuchillo {base_valve} — {opening} % de apertura"
    q = env.get("U", 0.0) * math.pi * R * R * 3600
    sub = a.subtitle or (f"asiento: {names.get(design or 'cad', design)}   ·   pulpa (Bingham, 1770 kg/m³)"
                         + (f"   ·   {q:.0f} m³/h" if opening and "U" in env and env.get("U", 0) < 5 else
                            "   ·   150 psi aguas arriba"))
    p.add_text(title, position=(0.03, 0.93), viewport=True, font_size=20, color="white", font="arial")
    p.add_text(sub, position=(0.03, 0.885), viewport=True, font_size=12, color="#c9d3df", font="arial")
    ttext = p.add_text("", position=(0.03, 0.04), viewport=True, font_size=12, color="#c9d3df", font="arial")
    p.add_text("flujo →", position=(0.80, 0.04), viewport=True, font_size=12, color="#8fb3d9", font="arial")

    # camera: from the side of the pipe, a little above and upstream, sweeping
    # about the vertical axis (azimuth measured from +x towards +z)
    focal = np.array([0.0, -0.1 * R, z0 + 0.42 * (z1 - z0)])
    dist = 1.15 * (z1 - z0)
    el = math.radians(a.elevation)

    def camera(frac):
        az = math.radians(a.azimuth + a.orbit * frac)
        pos = focal + dist * np.array([math.cos(az) * math.cos(el), math.sin(el), math.sin(az) * math.cos(el)])
        p.camera_position = [tuple(pos), tuple(focal), (0, 1, 0)]
        p.camera.view_angle = 30.0

    if a.preview:
        camera(0.5)
        ttext.input = f"t = {steps[-1][0]:.3f} s"
        p.screenshot(out)
        print("PNG:", out)
        return

    p.open_movie(out, framerate=Q["fps"], quality=8)
    sub_n = Q["sub"]
    n_frames = (len(vols) - 1) * sub_n + 1
    hold = int(a.hold * Q["fps"])
    total = hold + n_frames
    k = 0
    for i in range(hold):  # title over the first snapshot
        camera(0.0)
        vol_img.point_data["|u| [m/s]"][:] = vols[0]
        ttext.input = f"t = {steps[0][0]:.3f} s"
        p.write_frame()
        k += 1
    for j in range(n_frames):
        i0, w = divmod(j, sub_n)
        w = w / sub_n
        val = vols[i0] if w == 0 else (1 - w) * vols[i0] + w * vols[i0 + 1]
        t = steps[i0][0] if w == 0 else (1 - w) * steps[i0][0] + w * steps[i0 + 1][0]
        vol_img.point_data["|u| [m/s]"][:] = val
        vol_img.Modified()
        camera((k + 1) / total)
        ttext.input = f"t = {t:.3f} s"
        p.write_frame()
        k += 1
        print(f"  frame {k}/{total}", end="\r", flush=True)
    p.close()
    print("\nMP4:", out)


if __name__ == "__main__":
    main()
