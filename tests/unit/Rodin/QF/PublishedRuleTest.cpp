/**
 * @file
 * @brief Checks our moment oracle against externally published rules.
 *
 * Every other test compares a rule against moments derived here. That is
 * circular in one respect: a rule and an oracle built on the same mistaken
 * reference element agree with each other perfectly, and the whole suite
 * passes. The oracle-free property tests narrow that, but they still only
 * compare Rodin against Rodin.
 *
 * This closes it from outside. The rules below are the published
 * Xiao-Gimbutas rules, taken from the tables distributed with modepy
 * (https://github.com/inducer/modepy, MIT, Copyright Andreas Kloeckner) which
 * cite H. Xiao and Z. Gimbutas, "A numerical algorithm for the construction of
 * efficient quadrature rules in two and higher dimensions", Computers &
 * Mathematics with Applications 59 (2010) 663-676. They are stored there on an
 * equilateral reference element; the values here have been mapped onto Rodin's
 * unit simplex through modepy's own equilateral-to-unit map followed by the
 * biunit-to-unit scaling, with the weights carrying both Jacobians.
 *
 * If these integrate correctly under our oracle, then Rodin's reference
 * element and moment formulas agree with the published ones.
 */
